/**
 * QA3: alle neuen Konfigurationsbefehle der Runde (ccna, wan) auf einem Gerät –
 * fehlerfrei annehmen, Render/Replay, `.nsim`-Round-Trip, Kopieren/Einfügen und
 * vollständige Rücknahme per `no`-Form bis zur unveränderten Ausgangs-Konfiguration.
 */

export const strip = (x: string): string => x.replace(/Current configuration.*\n/, '');

export function apply(c: Cli, lines: string[]): void {
  c.run('enable', 'configure terminal');
  for (const l of lines) {
    const out = c.s.input(l);
    expect(out, `${l} -> ${out}`).not.toMatch(/^%|\n%/);
  }
  c.run('end');
}

