/** Switch + Router mit allen neuen Befehlen (SW_CFG/R_CFG). */
export function fullLab(seed = 7) {
  const e = new Engine({ seed });
  const s1 = cli(e, 'SW1');
  const r = wanRouter(e, 'R1');
  const rc = { ...r, out: () => '', cfg: () => '' } as unknown as Cli;
  apply(s1, SW_CFG);
  apply(rc, R_CFG);
  return { e, s1, r, rc };
}
